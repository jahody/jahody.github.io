// Stage 2, the port of 2_taxonomize.py: each model proposes taxonomies, the user picks axes and
// adds comments, and the refiner model merges the chosen proposals into final taxonomies.
// Prompt text is copied verbatim from the Python.

import { callJson, type CallOptions } from './llm';
import type { Axis, Paper, Proposal, Settings, TaxNode, Taxonomy } from './types';
import { dumps, slugifyModel } from './util';

export const TAXONOMY_SCHEMA_EXAMPLE = `{
  "chapter": "1",
  "name": "Top Level Category",
  "description": "2-3 sentence description of what this category covers.",
  "items": [
    {
      "name": "subcategory_name",
      "chapter": "1.1",
      "description": "2-3 sentence description.",
      "phrases": ["key phrase 1", "key phrase 2"],
      "hard_negative": "What does NOT belong here and why."
    },
    {
      "name": "another_subcategory",
      "chapter": "1.2",
      "description": "2-3 sentence description.",
      "items": [
        {
          "name": "leaf_category",
          "chapter": "1.2(a)",
          "description": "2-3 sentence description.",
          "phrases": ["phrase 1", "phrase 2"],
          "hard_negative": "What does NOT belong."
        }
      ]
    }
  ]
}`;

export const SYSTEM_MESSAGE =
  'You are an expert research taxonomist. Given a collection of academic papers, ' +
  'create multiple distinct hierarchical taxonomies that organize them in fundamentally ' +
  'different ways. Respond with valid JSON only.';

export const REFINE_SYSTEM =
  'You are an expert research taxonomist. Given multiple taxonomy proposals generated ' +
  'by different models, select the best organizing perspectives, combine the strongest ' +
  'categorization choices, and produce polished final taxonomies. Respond with valid JSON only.';

export function buildPrompt(papers: Paper[], queryName: string): string {
  let papersText = '';
  for (const p of papers) papersText += `\n### ${p.title} (arxiv: ${p.id})\n${p.content}\n---\n`;

  return `Here are ${papers.length} papers on the topic "${queryName}" for reference:

${papersText}

Create DISTINCT category taxonomies suited for classifying these papers.
Each taxonomy should use a fundamentally different organizing principle. Propose as many genuinely distinct perspectives as you see fit.

Requirements:
- Output a JSON object with a "taxonomies" key containing an array of taxonomy objects
- Each taxonomy object has: "perspective" (short name), "description" (1 sentence), and "categories" (the taxonomy array)
- Each taxonomy's "categories" is a JSON array (2-3 levels deep) following the schema below
- Each leaf category needs: name (snake_case), chapter, description (2-3 sentences), phrases (key terms), hard_negative (what does NOT belong and why)
- Chapter numbering: "1", "1.1", "1.1.1", "1.1(a)" for sub-items at the same level
- Aim for 5-15 leaf categories per taxonomy depending on paper diversity
- Use snake_case for category names
- Do NOT assign papers to categories — categories should be defined by their descriptions, phrases, and hard_negatives only

Single category schema example:
${TAXONOMY_SCHEMA_EXAMPLE}

Output format:
{
  "taxonomies": [
    {
      "perspective": "by_methodology",
      "description": "Organizes papers by their core technical approach.",
      "categories": [ ... ]
    }
  ]
}`;
}

export function buildRefinePrompt(proposals: Proposal[], queryName: string, comments: Record<string, string>): string {
  let proposalsText = '';
  proposals.forEach((entry, i) => {
    proposalsText += `\n## Proposal ${i + 1}: "${entry.perspective}" from ${slugifyModel(entry.model)}\n`;
    if (entry.description) proposalsText += `_${entry.description}_\n`;
    proposalsText += `\`\`\`json\n${dumps(entry.categories)}\n\`\`\`\n---\n`;
  });

  let commentsText = '';
  const entries = Object.entries(comments).filter(([, c]) => c.trim());
  if (entries.length) {
    commentsText = '\n## Human Comments (incorporate these when building the taxonomies)\n';
    for (const [perspective, comment] of entries) commentsText += `- **${perspective}**: ${comment}\n`;
    commentsText += '\n';
  }

  return `Here are ${proposals.length} taxonomy proposals for classifying papers on "${queryName}", generated by different models using different organizing perspectives:

${proposalsText}
${commentsText}
Your task: select the BEST and most useful organizing perspectives from the proposals above, then produce polished, refined versions of each. Discard redundant or overlapping perspectives — keep only those that are genuinely distinct. Keep as many or as few as warranted.

CRITICAL — the final taxonomies MUST be fundamentally different from each other:
- Each must use a genuinely distinct organizing principle
- If two proposals share a similar angle, merge them into one
- The top-level categories of each taxonomy should have minimal overlap
- A reader should be able to look at just the top-level category names and immediately see they organize the papers along completely different axes
- These taxonomies will be used to classify individual papers — prefer perspectives where the categories are mutually exclusive and clearly distinguishable

For each selected taxonomy:
- Combine the best categorization choices from any model that used a similar perspective
- Improve descriptions, phrases, and hard_negatives where needed
- Maintain 2-3 levels of hierarchy, 5-15 leaf categories
- Do NOT assign papers to categories — leave the "papers" field out entirely

Output a JSON object:
{
  "taxonomies": [
    {
      "perspective": "perspective_name",
      "description": "1 sentence explaining this organizing angle.",
      "categories": [ ... same schema as input ... ]
    }
  ]
}`;
}

/** Normalize an LLM response into a list of taxonomy entries (extract_taxonomies). */
export function extractTaxonomies(result: unknown): unknown[] {
  if (Array.isArray(result)) return result;
  if (result && typeof result === 'object') return ((result as any).taxonomies as unknown[]) ?? [];
  return [];
}

/** (perspective, categories, description) from one entry (tax_fields). */
export function taxFields(tax: unknown, i = 0): { perspective: string; categories: TaxNode[]; description: string } {
  if (!tax || typeof tax !== 'object' || Array.isArray(tax)) {
    return { perspective: `taxonomy_${i + 1}`, categories: Array.isArray(tax) ? (tax as TaxNode[]) : [], description: '' };
  }
  const t = tax as any;
  return {
    perspective: String(t.perspective ?? `taxonomy_${i + 1}`),
    categories: Array.isArray(t.categories) ? t.categories : [],
    description: String(t.description ?? ''),
  };
}

type Ctx = Pick<CallOptions, 'key' | 'signal' | 'onUsage' | 'onRetry'>;

/** Phase 1: every model proposes taxonomies in parallel. Failed models are reported, not fatal. */
export async function proposeTaxonomies(
  papers: Paper[],
  queryName: string,
  s: Settings,
  ctx: Ctx,
  onModelDone?: (model: string, error?: string) => void,
): Promise<Proposal[]> {
  const prompt = buildPrompt(papers, queryName);
  const results = await Promise.all(
    s.models.map(async (model) => {
      try {
        const result = await callJson({
          ...ctx,
          model,
          system: SYSTEM_MESSAGE,
          user: prompt,
          temperature: s.generationTemperature,
          maxTokens: s.generationMaxTokens,
        });
        const proposals = extractTaxonomies(result).map((t, i) => ({ model, ...taxFields(t, i) }));
        onModelDone?.(model);
        return proposals;
      } catch (e) {
        if ((e as Error).name === 'AbortError') throw e;
        onModelDone?.(model, (e as Error).message);
        return [];
      }
    }),
  );
  return results.flat().filter((p) => p.categories.length);
}

/** Distinct perspectives with how many proposals share each one (prompt_axis_selection). */
export function axesFromProposals(proposals: Proposal[]): Axis[] {
  const axes = new Map<string, Axis>();
  for (const p of proposals) {
    const a = axes.get(p.perspective);
    if (a) a.proposals++;
    else axes.set(p.perspective, { perspective: p.perspective, description: p.description, proposals: 1, selected: true, comment: '' });
  }
  return [...axes.values()];
}

/**
 * Phase 2: the refiner merges the selected proposals. With fewer than two proposals there is
 * nothing to merge (the Python skips this step), so they become the taxonomies as they are.
 */
export async function refineTaxonomies(proposals: Proposal[], axes: Axis[], queryName: string, s: Settings, ctx: Ctx): Promise<Taxonomy[]> {
  const chosen = new Set(axes.filter((a) => a.selected).map((a) => a.perspective));
  const selected = proposals.filter((p) => chosen.has(p.perspective));
  if (selected.length < 2) return selected.map((p) => ({ name: p.perspective, description: p.description, items: p.categories }));

  const comments = Object.fromEntries(axes.filter((a) => a.selected && a.comment.trim()).map((a) => [a.perspective, a.comment.trim()]));
  const result = await callJson({
    ...ctx,
    model: s.refiner,
    system: REFINE_SYSTEM,
    user: buildRefinePrompt(selected, queryName, comments),
    temperature: s.refinerTemperature,
    maxTokens: s.generationMaxTokens,
  });
  return extractTaxonomies(result)
    .map((t, i) => taxFields(t, i))
    .filter((t) => t.categories.length)
    .map((t) => ({ name: t.perspective, description: t.description, items: t.categories }));
}
